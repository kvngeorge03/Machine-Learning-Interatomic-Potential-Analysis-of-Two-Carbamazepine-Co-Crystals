# ---------------------------------------------------------

def calculate_ring_pair(structure, ring1, ring2):

    coords1 = unwrap_ring(structure, ring1)
    coords2 = unwrap_ring(structure, ring2)

    c1, n1 = get_plane(coords1)
    c2, n2 = get_plane(coords2)

    # -----------------------------------------------------
    # Translate ring 2 to the closest periodic image
    # relative to ring 1
    # -----------------------------------------------------

    frac_c1 = structure.lattice.get_fractional_coords(c1)
    frac_c2 = structure.lattice.get_fractional_coords(c2)

    delta_frac = frac_c2 - frac_c1
