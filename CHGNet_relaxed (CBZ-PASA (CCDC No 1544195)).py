# ------------------------------------------------------------

for atoms in md_frames:

    cell = atoms.get_cell().array
    current_positions = atoms.get_positions()

    # Convert reference and current Cartesian coordinates
    # to fractional coordinates
    frac_reference = np.linalg.solve(
        cell.T,
        reference_positions.T
    ).T

    frac_current = np.linalg.solve(
        cell.T,
        current_positions.T
    ).T

    # Fractional displacement
    frac_difference = frac_current - frac_reference

    # Minimum-image convention
    frac_difference -= np.round(frac_difference)

    # Convert displacement back to Cartesian coordinates
    cart_difference = frac_difference @ cell

    # Magnitude of displacement for every atom
    distances = np.linalg.norm(
        cart_difference,
        axis=1
    )

