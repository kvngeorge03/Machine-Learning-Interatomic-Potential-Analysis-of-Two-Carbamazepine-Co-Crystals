# ---------------------------------------------------------

def get_plane(coords):
    centroid = np.mean(coords, axis=0)
    centered = coords - centroid

    _, _, vh = np.linalg.svd(
        centered,
        full_matrices=False
    )

    normal = vh[-1]
    normal = normal / np.linalg.norm(normal)

    return centroid, normal


