    # Plane fitting using SVD
    def plane_normal(coords):
        centered = coords - np.mean(coords, axis=0)
        _, _, vh = np.linalg.svd(
            centered,
            full_matrices=False
        )
        normal = vh[-1]
        normal = normal / np.linalg.norm(normal)
        return normal

