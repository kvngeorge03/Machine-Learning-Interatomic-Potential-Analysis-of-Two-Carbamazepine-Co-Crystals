def minimum_image_distance(structure, i, j):
    frac_i = structure.frac_coords[i]
    frac_j = structure.frac_coords[j]
    delta = frac_j - frac_i
    delta -= np.round(delta)
    cart_delta = np.dot(delta, structure.lattice.matrix)
    return np.linalg.norm(cart_delta)


def minimum_image_angle(structure, donor, hydrogen, acceptor):
    frac_D = structure.frac_coords[donor]
    frac_H = structure.frac_coords[hydrogen]
    frac_A = structure.frac_coords[acceptor]

    dH = frac_H - frac_D
    dH -= np.round(dH)

