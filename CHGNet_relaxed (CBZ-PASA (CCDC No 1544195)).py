# -------------------------------------------------------------------------
# 3. Function to change H···O distance
# -------------------------------------------------------------------------

def set_HO_distance_exp(atoms_in, target_distance):

    atoms_new = atoms_in.copy()

    H_position = atoms_new.positions[H_idx].copy()
    O_acc_position = atoms_new.positions[O_acc_idx].copy()

    # Existing H -> O vector
    HO_vector = O_acc_position - H_position

    current_distance = np.linalg.norm(HO_vector)

    if current_distance == 0:
        raise ValueError(
            "Current H···O distance is zero."
        )

    # Unit vector along H -> O direction
    HO_unit = HO_vector / current_distance

    # Move O380 to requested distance
    atoms_new.positions[O_acc_idx] = (
        H_position +
        target_distance * HO_unit
    )

    return atoms_new


# -------------------------------------------------------------------------
# 4. CHGNet energy function
# -------------------------------------------------------------------------

def calculate_chgnet_energy_exp(ase_atoms):

    structure = AseAtomsAdaptor.get_structure(
        ase_atoms
    )

    prediction = model_exp.predict_structure(
        structure,
        task="ef"
    )

    energy_per_atom = float(
        prediction["e"]
    )

    total_energy = (
        energy_per_atom * len(structure)
    )

    return total_energy, energy_per_atom


