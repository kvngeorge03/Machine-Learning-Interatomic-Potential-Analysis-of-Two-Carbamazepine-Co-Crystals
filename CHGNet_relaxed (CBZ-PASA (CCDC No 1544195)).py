    n2 = plane_normal(coords2)

    # Plane angle
    cos_angle = np.abs(np.dot(n1, n2))
    cos_angle = np.clip(cos_angle, -1.0, 1.0)
    plane_angle = np.degrees(np.arccos(cos_angle))

    # Interplanar separation
    midpoint_vector = centroid_vector
    plane_separation = np.abs(np.dot(midpoint_vector, n1))

    # Lateral offset
    lateral_offset = np.sqrt(
        max(
            centroid_distance**2 -
            plane_separation**2,
            0
        )
    )

    return (
        centroid_distance,
        plane_separation,
        lateral_offset,
        plane_angle
    )

