def angle_three_points(a, b, c):
    """
    Calculate angle A-B-C in degrees.
    """
    v1 = a - b
    v2 = c - b

    norm1 = np.linalg.norm(v1)
    norm2 = np.linalg.norm(v2)

    if norm1 == 0 or norm2 == 0:
        return np.nan

    cosine = np.dot(v1, v2) / (norm1 * norm2)

    cosine = np.clip(cosine, -1.0, 1.0)

    return np.degrees(
        np.arccos(cosine)
    )


def mic_vector(atoms, i, j):
    """
    Minimum-image vector from atom i to atom j.
    """
    cell = atoms.get_cell().array

    positions = atoms.get_positions()

    frac = np.linalg.solve(
        cell.T,
        positions.T
    ).T

    df = frac[j] - frac[i]

    df -= np.round(df)

    return df @ cell


