# ------------------------------------------------------------
# Function to calculate pair-distance histogram
# with periodic minimum-image convention
# ------------------------------------------------------------

def pair_distance_histogram(frames, indices_a, indices_b,
                            r_edges, same_species=False):

    histogram = np.zeros(len(r_edges) - 1)

    total_pairs = 0

    for atoms in frames:

        positions = atoms.get_positions()
        cell = atoms.get_cell().array

        # Fractional coordinates
        fractional = np.linalg.solve(
            cell.T,
            positions.T
        ).T

        # Pair combinations
        if same_species:
            pairs = [
                (i, j)
                for ii, i in enumerate(indices_a)
                for j in indices_a[ii + 1:]
            ]
        else:
            pairs = [
                (i, j)
                for i in indices_a
                for j in indices_b
            ]

        for i, j in pairs:

            df = fractional[j] - fractional[i]

            # Minimum-image convention
            df -= np.round(df)

            # Cartesian distance
            dr_cart = df @ cell

            distance = np.linalg.norm(dr_cart)

            if distance < r_edges[-1]:
                histogram += np.histogram(
                    [distance],
                    bins=r_edges
                )[0]

            total_pairs += 1

    return histogram, total_pairs


# ------------------------------------------------------------
# Calculate RDF-like normalized distributions
# ------------------------------------------------------------

