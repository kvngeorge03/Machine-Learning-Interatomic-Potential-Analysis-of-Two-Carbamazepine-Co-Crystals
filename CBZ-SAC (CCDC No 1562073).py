# ------------------------------------------------------------
# Two molecular components of the cocrystal
# ------------------------------------------------------------

molecule_A = sorted(
    component_A | component_B
)

molecule_B = sorted(
    component_C | component_D
)

print("=" * 75)
print("INTERMOLECULAR CONTACT PERSISTENCE")
print("=" * 75)

print(
    f"Molecular component A: {len(molecule_A)} atoms"
)

print(
    f"Molecular component B: {len(molecule_B)} atoms"
)

# ------------------------------------------------------------
# Atom symbols
# ------------------------------------------------------------

symbols = np.array(
    md_frames[0].get_chemical_symbols()
)

# ------------------------------------------------------------
# Define contact cutoff
#
# We use a broad 3.6 Å cutoff for intermolecular
# non-bonded contacts.
#
# This is NOT a Hirshfeld fingerprint.
# ------------------------------------------------------------

CONTACT_CUTOFF = 3.6

# ------------------------------------------------------------
# Calculate experimental/reference intermolecular contacts
# from the first MD frame
# ------------------------------------------------------------

reference = md_frames[0]

cell = reference.get_cell().array
positions = reference.get_positions()

contacts = []

for i in molecule_A:

    for j in molecule_B:

        # Fractional displacement
        fi = np.linalg.solve(
            cell.T,
            positions[i]
        )

        fj = np.linalg.solve(
            cell.T,
            positions[j]
        )

        df = fj - fi

        # Minimum image
        df -= np.round(df)

        # Cartesian displacement
        vector = df @ cell

        distance = np.linalg.norm(vector)

        if distance <= CONTACT_CUTOFF:

            pair = "".join(
                sorted(
                    [symbols[i], symbols[j]]
                )
            )

            contacts.append({
                "Atom_i": i,
                "Atom_j": j,
                "Element_i": symbols[i],
                "Element_j": symbols[j],
                "Contact_type": pair,
                "Reference_distance_A": distance
            })

contacts_df = pd.DataFrame(contacts)

print(
    f"\nReference intermolecular contacts: "
    f"{len(contacts_df)}"
)

# ------------------------------------------------------------
# Track every reference contact during MD
# ------------------------------------------------------------

results = []

for _, contact in contacts_df.iterrows():

    i = int(contact["Atom_i"])
    j = int(contact["Atom_j"])

    distances = []

    for atoms in md_frames:

        cell = atoms.get_cell().array
        positions = atoms.get_positions()

        fi = np.linalg.solve(
            cell.T,
            positions[i]
        )

        fj = np.linalg.solve(
            cell.T,
            positions[j]
        )

        df = fj - fi

        df -= np.round(df)

        vector = df @ cell

        distance = np.linalg.norm(vector)

        distances.append(distance)

    distances = np.array(distances)

    persistence = (
        100 *
        np.mean(
            distances <= CONTACT_CUTOFF
        )
    )

    results.append({
        "Atom_i": i,
        "Atom_j": j,
        "Element_i": symbols[i],
        "Element_j": symbols[j],
        "Contact_type": contact["Contact_type"],
        "Reference_distance_A":
            contact["Reference_distance_A"],
        "Mean_distance_A":
            np.mean(distances),
        "Std_distance_A":
            np.std(distances),
        "Minimum_distance_A":
            np.min(distances),
        "Maximum_distance_A":
            np.max(distances),
        "Persistence_percent":
            persistence
    })

contact_persistence_df = pd.DataFrame(results)

