def unwrap_ring(structure, indices):

    frac = structure.frac_coords[indices].copy()

    reference = frac[0].copy()

    for i in range(1, len(frac)):

        delta = frac[i] - reference

        delta -= np.round(delta)

        frac[i] = reference + delta

    coords = np.dot(
        frac,
        structure.lattice.matrix
    )

    return coords


# ---------------------------------------------------------
# Calculate ring plane
# ---------------------------------------------------------

def get_plane(coords):

    centroid = np.mean(coords, axis=0)

    centered = coords - centroid

    _, _, vh = np.linalg.svd(
        centered,
        full_matrices=False
    )

    normal = vh[-1]

    normal = normal / np.linalg.norm(normal)

    return centroid, normal


# ---------------------------------------------------------
# Calculate geometry between two rings
# ---------------------------------------------------------

def calculate_ring_pair(structure, ring1, ring2):

    coords1 = unwrap_ring(
        structure,
        ring1
    )

    coords2 = unwrap_ring(
        structure,
        ring2
    )

    c1, n1 = get_plane(coords1)
    c2, n2 = get_plane(coords2)

    # -----------------------------------------------------
    # Translate ring 2 to the closest periodic image
    # relative to ring 1
    # -----------------------------------------------------

    frac_c1 = structure.lattice.get_fractional_coords(c1)
    frac_c2 = structure.lattice.get_fractional_coords(c2)

    delta_frac = frac_c2 - frac_c1

    delta_frac -= np.round(delta_frac)

    delta_cart = np.dot(
        delta_frac,
        structure.lattice.matrix
    )

    c2_near = c1 + delta_cart

    centroid_distance = np.linalg.norm(
        delta_cart
    )

    # -----------------------------------------------------
    # Plane angle
    # -----------------------------------------------------

    cos_angle = np.abs(
        np.dot(n1, n2)
    )

    cos_angle = np.clip(
        cos_angle,
        -1.0,
        1.0
    )

    plane_angle = np.degrees(
        np.arccos(cos_angle)
    )

    # -----------------------------------------------------
    # Interplanar separation
    # -----------------------------------------------------

    plane_separation = np.abs(
        np.dot(
            delta_cart,
            n1
        )
    )

    # -----------------------------------------------------
    # Lateral offset
    # -----------------------------------------------------

