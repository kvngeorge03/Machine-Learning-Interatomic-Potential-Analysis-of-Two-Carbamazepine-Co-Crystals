# -------------------------------------------------------------------------
# 2. Function to set H···O distance
# -------------------------------------------------------------------------

def set_HO_distance(atoms_in, target_distance):
    """
    Create a copy of the structure and move O93 along the
    existing H33 -> O93 direction to obtain the requested H···O distance.
    """

    atoms_new = atoms_in.copy()

    H_position = atoms_new.positions[H_idx].copy()
    O_position = atoms_new.positions[O_idx].copy()

    # Existing H -> O vector
    HO_vector = O_position - H_position
    current_HO = np.linalg.norm(HO_vector)

    if current_HO == 0:
        raise ValueError("H···O distance is zero; cannot define direction.")

    # Unit vector along H -> O
    HO_unit = HO_vector / current_HO

    # New O position
    atoms_new.positions[O_idx] = (
        H_position + target_distance * HO_unit
    )

    return atoms_new


