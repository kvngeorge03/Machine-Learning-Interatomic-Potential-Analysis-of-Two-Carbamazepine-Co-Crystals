def ring_geometry(structure, ring1, ring2):

    coords1 = structure.cart_coords[ring1]
    coords2 = structure.cart_coords[ring2]

    # Ring centroids
    c1 = np.mean(coords1, axis=0)
    c2 = np.mean(coords2, axis=0)

    # Minimum-image centroid displacement
    frac1 = structure.lattice.get_fractional_coords(c1)
    frac2 = structure.lattice.get_fractional_coords(c2)

    delta = frac2 - frac1
    delta -= np.round(delta)

    centroid_vector = np.dot(
        delta,
        structure.lattice.matrix
    )

    centroid_distance = np.linalg.norm(
        centroid_vector
    )

    # Plane fitting using SVD
    def plane_normal(coords):

        centered = coords - np.mean(coords, axis=0)

        _, _, vh = np.linalg.svd(
            centered,
            full_matrices=False
        )

        normal = vh[-1]
        normal = normal / np.linalg.norm(normal)

        return normal

    n1 = plane_normal(coords1)
    n2 = plane_normal(coords2)

    # Plane angle
    cos_angle = np.abs(np.dot(n1, n2))
    cos_angle = np.clip(cos_angle, -1.0, 1.0)

    plane_angle = np.degrees(
        np.arccos(cos_angle)
    )

    # Interplanar separation
    midpoint_vector = centroid_vector

    plane_separation = np.abs(
        np.dot(midpoint_vector, n1)
    )

    # Lateral offset
    lateral_offset = np.sqrt(
        max(
            centroid_distance**2 -
            plane_separation**2,
            0
        )
    )

    return (
        centroid_distance,
        plane_separation,
        lateral_offset,
        plane_angle
    )

