# ------------------------------------------------------------
# Store displacement for every atom and every frame
# ------------------------------------------------------------

all_displacements = np.zeros(
    (len(md_frames), n_atoms)
)

# ------------------------------------------------------------
# Calculate periodic minimum-image displacements
# ------------------------------------------------------------

for frame_index, atoms in enumerate(md_frames):

    cell = atoms.get_cell().array
    current_positions = atoms.get_positions()

    # Fractional coordinates
    frac_reference = np.linalg.solve(
        cell.T,
        reference_positions.T
    ).T

    frac_current = np.linalg.solve(
        cell.T,
        current_positions.T
    ).T

    # Fractional displacement
    frac_difference = (
        frac_current - frac_reference
    )

    # Minimum-image convention
    frac_difference -= np.round(
        frac_difference
    )

    # Cartesian displacement
    cart_difference = (
        frac_difference @ cell
    )

    # Magnitude
    distances = np.linalg.norm(
        cart_difference,
        axis=1
    )

    all_displacements[frame_index, :] = distances


# ------------------------------------------------------------
# Per-atom statistics
# ------------------------------------------------------------

mean_disp = np.mean(
    all_displacements,
    axis=0
)

max_disp = np.max(
    all_displacements,
    axis=0
)

final_disp = all_displacements[-1, :]

rms_disp = np.sqrt(
    np.mean(
        all_displacements**2,
        axis=0
    )
)


