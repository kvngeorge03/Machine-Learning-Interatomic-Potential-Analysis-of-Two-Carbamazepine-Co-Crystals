def minimum_image_vector(position1, position2, cell):
    """
    Return minimum-image vector from position1 to position2.
    """
    fractional = np.linalg.solve(cell.T, position2 - position1)
    fractional -= np.round(fractional)
    return np.dot(fractional, cell)


def distance_mic(position1, position2, cell):
    vector = minimum_image_vector(position1, position2, cell)
    return np.linalg.norm(vector)


def hydrogen_bond_angle(D, H, A, cell):
    """
    Calculate D-H...A angle using minimum-image vectors.
    """

    # H -> D
    HD = minimum_image_vector(H, D, cell)

    # H -> A
    HA = minimum_image_vector(H, A, cell)

    cos_angle = np.dot(HD, HA) / (
        np.linalg.norm(HD) * np.linalg.norm(HA)
    )

    cos_angle = np.clip(cos_angle, -1.0, 1.0)

    return np.degrees(np.arccos(cos_angle))


