def minimum_image_distance(structure, i, j):
    """
    Calculate minimum-image distance between two atoms
    in a periodic crystal.
    """
    frac_i = structure.frac_coords[i]
    frac_j = structure.frac_coords[j]

    delta = frac_j - frac_i
    delta -= np.round(delta)

    cart_delta = np.dot(
        delta,
        structure.lattice.matrix
    )

    return np.linalg.norm(cart_delta)


def minimum_image_angle(structure, donor, hydrogen, acceptor):
    """
    Calculate D-H...A angle using minimum-image convention.
    """

    frac_D = structure.frac_coords[donor]
    frac_H = structure.frac_coords[hydrogen]
    frac_A = structure.frac_coords[acceptor]

    # H relative to donor
    dH = frac_H - frac_D
    dH -= np.round(dH)

    # A relative to H
    HA = frac_A - frac_H
    HA -= np.round(HA)

    v_DH = np.dot(
        dH,
        structure.lattice.matrix
    )

    v_HA = np.dot(
        HA,
        structure.lattice.matrix
    )

    # Vectors H->D and H->A
    v_HD = -v_DH
    v_HA = v_HA

    cosine = np.dot(v_HD, v_HA) / (
        np.linalg.norm(v_HD) *
        np.linalg.norm(v_HA)
    )

    cosine = np.clip(cosine, -1.0, 1.0)

    return np.degrees(
        np.arccos(cosine)
    )


def analyze_hbond(structure, donor, hydrogen, acceptor):

    DH = minimum_image_distance(
        structure,
        donor,
        hydrogen
    )

    HA = minimum_image_distance(
        structure,
        hydrogen,
        acceptor
    )

    DA = minimum_image_distance(
        structure,
        donor,
        acceptor
    )

    angle = minimum_image_angle(
        structure,
        donor,
        hydrogen,
        acceptor
    )

    return DH, HA, DA, angle


